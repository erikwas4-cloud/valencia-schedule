export function getEventsForDate(date: string): ClassEvent[] {
  return schedule
    .filter(e => e.date === date)
    .sort((a, b) => a.startTime.localeCompare(b.startTime))
}

export function getEventsForWeek(monday: string): ClassEvent[] {
  const start = new Date(monday)
  const dates: string[] = []
  for (let i = 0; i < 5; i++) {
    const d = new Date(start)
    d.setDate(start.getDate() + i)
    dates.push(d.toISOString().slice(0, 10))
  }
  return schedule.filter(e => dates.includes(e.date)).sort((a, b) => {
    if (a.date !== b.date) return a.date.localeCompare(b.date)
    return a.startTime.localeCompare(b.startTime)
  })
}

export function getMondayOf(date: Date): string {
  const d = new Date(date)
  const day = d.getDay()
  const diff = day === 0 ? -6 : 1 - day
  d.setDate(d.getDate() + diff)
  return d.toISOString().slice(0, 10)
}
